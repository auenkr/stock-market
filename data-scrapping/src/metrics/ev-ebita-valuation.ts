export async function ebitaStockValuationModel(companyData: CompanyDataType) {
  // const EV = companyData.summary.marketCap + companyData.summary.debt - companyData.summary.cash
  // const response = await axios.get<CompanyPriceDataType>(`${BASE_URL}/api/company/${companyData.refId}/chart/?q=Price&days=10000&consolidated=true`) // days = 10000 for MAX values
  // const companyPrice = response.data as CompanyPriceDataType
  const companyPrice: CompanyPriceDataType = companyPriceData;

  let marketCap: Record<string, NumberDataType> = {};
  let debt: Record<string, NumberDataType> = {};
  let cash: Record<string, NumberDataType> = {};

  companyData.shareholdingPatternStatements.forEach((statement) => {
    const price = getCompanyPrice(companyPrice, statement.timePeriod);
    marketCap[statement.timePeriod] = {
      amount: price * statement.noOfShareHolders.amount,
      baseValue: statement.noOfShareHolders.baseValue,
    };
  });

  companyData.balanceSheetStatements.forEach((statement) => {
    debt[statement.timePeriod] = {
      amount: (statement.borrowings?.value?.amount || 0) * 10000000, // convert to lakh
      baseValue: statement.borrowings?.value?.baseValue ? "one" : "none",
    };

    cash[statement.timePeriod] = {
      amount:
        (statement.otherAssets.other["Cash Equivalents"]?.amount || 0) *
        10000000, // convert to crore
      baseValue: statement.otherAssets.other["Cash Equivalents"]?.baseValue
        ? "one"
        : "none",
    };
  });

  const EV = Object.keys(marketCap).map((key) => {
    const marketCapValue = marketCap[key]?.amount || 0;
    const debtValue = debt[key]?.amount || 0;
    const cashValue = cash[key]?.amount || 0;
    return {
      timePeriod: key,
      // amount: marketCapValue + debtValue - cashValue,
      amount: marketCapValue,
      baseValue: "one",
    };
  });

  const EBITA = companyData.profitAndLossStatements.map((statement) => {
    return {
      timePeriod: statement.timePeriod,
      amount:
        (statement.profitBeforeTax.amount +
        statement.depreciation.amount +
        statement.interest.amount) * 10000000, // convert to ones
      baseValue:
        "one",
    };
  });

  console.log("EV: ", EV);
  console.log("EBITA: ", EBITA);
  const result = EV.map((ev) => {
    const result = ev.amount / (EBITA[0]?.amount || 0);
    return {
      timePeriod: ev.timePeriod,
      amount: result,
      baseValue: "one",
    };
  });
  console.log("result: ", result);
  return 0;
}

function getCompanyPrice(
  data: CompanyPriceDataType,
  timePeriod: string
): number {
  if (data.datasets[0]?.metric !== "Price") return 0;

  const monthNames: { [key: string]: number } = {
    Jan: 1,
    Feb: 2,
    Mar: 3,
    Apr: 4,
    May: 5,
    Jun: 6,
    Jul: 7,
    Aug: 8,
    Sep: 9,
    Oct: 10,
    Nov: 11,
    Dec: 12,
  };

  const parts = timePeriod.trim().split(" ");
  if (parts.length !== 2) return 0;

  const monthStr = parts[0] || "";
  const yearStr = parts[1] || "";
  const month = monthNames[monthStr];
  const year = parseInt(yearStr, 10);

  if (!month || isNaN(year)) return 0;

  const isWeekly = data.datasets[0]?.meta.is_weekly === true;
  const values = data.datasets[0]?.values || [];

  if (isWeekly) {
    const monthYearPrefix = `${year}-${String(month).padStart(2, "0")}-`;
    const firstWeekInMonth = values.find(([date, _]) =>
      date.startsWith(monthYearPrefix)
    );
    return firstWeekInMonth ? parseFloat(firstWeekInMonth[1]) || 0 : 0;
  } else {
    const targetDate = `${year}-${String(month).padStart(2, "0")}-01`;
    const dailyPrice = values.find(([date, _]) => date === targetDate);
    return dailyPrice ? parseFloat(dailyPrice[1]) || 0 : 0;
  }
}

