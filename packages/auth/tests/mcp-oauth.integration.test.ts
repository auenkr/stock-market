import assert from "node:assert/strict";
import { test, after } from "node:test";
import { createHash, createHmac, randomUUID } from "node:crypto";
import { hashPassword } from "better-auth/crypto";
import { verifyOAuthQueryParams } from "@better-auth/oauth-provider";
import { db, apiKey, oauthConsent } from "@stock-market/db";
import { eq } from "drizzle-orm";
import { authorizeAccountRequest } from "@stock-market/db/account-access";
import worker from "../../../apps/mcp/src/worker.js";

const origin = "http://localhost:3001";
const resource = "https://stock-market-mcp.auenkr.com/mcp";
const secret = "mcp-integration-secret-at-least-thirty-two-characters";
process.env.ENVIRONMENT = "dev";
process.env.BETTER_AUTH_URL = origin;
process.env.BETTER_AUTH_SECRET = secret;
process.env.MCP_ACCOUNT_SERVICE_SECRET = secret;
process.env.API_KEY_ENCRYPTION_SECRET = secret;
const { auth } = await import("../src/index.js");
const uid = randomUUID();
let clientId = "";
let cookie = "";
const call = (path: string, body?: unknown, signedIn = false, extra: Record<string, string> = {}) => auth.handler(new Request(`${origin}/api/auth${path}`, {
  method: body ? "POST" : "GET", headers: { origin, ...(body ? { "Content-Type": path === "/oauth2/token" ? "application/x-www-form-urlencoded" : "application/json" } : {}), ...(signedIn ? { cookie } : {}), ...extra }, ...(body ? { body: path === "/oauth2/token" ? new URLSearchParams(body as Record<string, string>).toString() : JSON.stringify(body) } : {}),
}));
const checkedJson = async (response: Response) => { const body = await response.json() as any; assert.equal(response.status, 200, JSON.stringify(body)); return body; };
const bridge = (token: string, overrides: Record<string, string> = {}) => {
  const body = { token }; const timestamp = String(Date.now());
  const signature = createHmac("sha256", secret).update(`${timestamp}.${JSON.stringify(body)}`).digest("hex");
  return call("/mcp/access", body, false, { "X-MCP-Timestamp": timestamp, "X-MCP-Signature": signature, ...overrides });
};
after(async () => { await db.$client`DELETE FROM oauth_client WHERE client_id = ${clientId}`; await db.$client`DELETE FROM "user" WHERE id = ${uid}`; await db.$client.end(); });

test("Better Auth account linking, PKCE, refresh, account quota and revocation", async () => {
  assert.match(process.env.INTEGRATION_DATABASE_URL || "", /stock_test_/);
  const password = await hashPassword("test-development-password");
  await db.$client`INSERT INTO "user" (id,name,email,email_verified,profile_completed,created_at,updated_at) VALUES (${uid},'OAuth tester',${`${uid}@auenkr.com`},true,true,now(),now())`;
  await db.$client`INSERT INTO account (id,user_id,account_id,provider_id,password,created_at,updated_at) VALUES (${randomUUID()},${uid},${uid},'credential',${password},now(),now())`;
  await db.$client`INSERT INTO usage_policy (id,request_limit) VALUES ('default',2) ON CONFLICT (id) DO UPDATE SET request_limit=2`;
  const metadata = await checkedJson(await call("/.well-known/oauth-authorization-server"));
  assert.equal(metadata.issuer, `${origin}/api/auth`);
  assert(metadata.code_challenge_methods_supported.includes("S256"));
  const redirectUri = "https://chatgpt.com/connector/oauth/test";
  const register = await call("/oauth2/register", { client_name: "ChatGPT test", redirect_uris: [redirectUri], token_endpoint_auth_method: "none", grant_types: ["authorization_code", "refresh_token"], response_types: ["code"], scope: "market:read offline_access" });
  const registration = await register.json() as any;
  assert([200,201].includes(register.status), JSON.stringify(registration));
  clientId = registration.client_id;
  const verifier = "a".repeat(64);
  const query = new URLSearchParams({ client_id: clientId, redirect_uri: redirectUri, response_type: "code", scope: "market:read offline_access", resource, state: "oauth-state", code_challenge_method: "S256", code_challenge: createHash("sha256").update(verifier).digest("base64url") });
  const anonymous = await call(`/oauth2/authorize?${query}`);
  assert.equal(anonymous.status, 302);
  const loginUrl = new URL(anonymous.headers.get("location")!, origin);
  assert.equal(loginUrl.pathname, "/connect/chatgpt");
  assert(await verifyOAuthQueryParams(loginUrl.search.slice(1), (await auth.$context).secret));
  assert.equal(await verifyOAuthQueryParams(`${loginUrl.search.slice(1)}&scope=admin`, (await auth.$context).secret), false);
  const login = await call("/sign-in/email", { email: `${uid}@auenkr.com`, password: "test-development-password" });
  await checkedJson(login);
  cookie = login.headers.getSetCookie().map(value => value.split(";")[0]).join("; ");
  const authorize = await call(`/oauth2/authorize?${query}`, undefined, true);
  assert.equal(authorize.status, 302);
  const consentUrl = new URL(authorize.headers.get("location")!, origin);
  assert.equal(consentUrl.pathname, "/connect/chatgpt/consent");
  const denied = await checkedJson(await call("/oauth2/consent", { accept: false, oauth_query: consentUrl.search.slice(1) }, true));
  assert.equal(new URL(denied.url).searchParams.get("error"), "access_denied");
  const next = await call(`/oauth2/authorize?${query}`, undefined, true);
  const accepted = await checkedJson(await call("/oauth2/consent", { accept: true, oauth_query: new URL(next.headers.get("location")!, origin).search.slice(1) }, true));
  const callback = new URL(accepted.url);
  assert.equal(callback.searchParams.get("state"), "oauth-state");
  assert.equal(callback.searchParams.get("iss"), `${origin}/api/auth`);
  const wrongResource = new URLSearchParams(query);
  wrongResource.set("resource", "https://unrelated.example/mcp");
  const resourceDenied = await call(`/oauth2/authorize?${wrongResource}`, undefined, true);
  assert.equal(new URL(resourceDenied.headers.get("location")!, origin).searchParams.get("error"), "invalid_target");
  const tokenBody = { grant_type: "authorization_code", client_id: clientId, code: callback.searchParams.get("code"), redirect_uri: redirectUri, code_verifier: verifier, resource };
  const tokenResponse = await call("/oauth2/token", tokenBody);
  const tokens = await checkedJson(tokenResponse);
  assert(tokens.access_token && tokens.refresh_token);
  const pkceQuery = new URLSearchParams(query);
  pkceQuery.set("prompt", "consent");
  const pkceAuthorize = await call(`/oauth2/authorize?${pkceQuery}`, undefined, true);
  const pkceConsent = await checkedJson(await call("/oauth2/consent", { accept: true, oauth_query: new URL(pkceAuthorize.headers.get("location")!, origin).search.slice(1) }, true));
  const pkceCode = new URL(pkceConsent.url).searchParams.get("code");
  const invalidPkce = await call("/oauth2/token", { ...tokenBody, code: pkceCode, code_verifier: "wrong".repeat(16) });
  assert.equal(invalidPkce.status, 401);
  assert.equal((await invalidPkce.json() as any).error_description, "code verification failed");
  assert.equal((await call("/mcp/access", { token: tokens.access_token })).status, 401);
  assert.equal((await bridge(tokens.access_token, { "X-MCP-Timestamp": "1" })).status, 401);
  assert.equal((await bridge(tokens.access_token + "tampered")).status, 401);
  const access = await checkedJson(await bridge(tokens.access_token));
  assert(access.apiKey.startsWith("sm_live_"));
  const [keyRecord] = await db.select().from(apiKey).where(eq(apiKey.keyHash, createHash("sha256").update(access.apiKey).digest("hex")));
  assert(keyRecord);
  assert.equal(keyRecord.userId, uid);
  const env = { DB_CONNECTION_URL: process.env.INTEGRATION_DATABASE_URL };
  assert.equal((await authorizeAccountRequest(access.apiKey, env, db.$client)).status, "allowed");
  assert.equal((await authorizeAccountRequest(access.apiKey, env, db.$client)).status, "allowed");
  assert.equal((await authorizeAccountRequest(access.apiKey, env, db.$client)).status, "limited");
  const refreshed = await checkedJson(await call("/oauth2/token", { grant_type: "refresh_token", client_id: clientId, refresh_token: tokens.refresh_token, resource }));
  assert.equal((await checkedJson(await bridge(refreshed.access_token))).apiKey, access.apiKey);
  const originalFetch = globalThis.fetch;
  globalThis.fetch = (async (input, init) => {
    const url = String(input);
    if (url === `${origin}/api/auth/mcp/access`) return auth.handler(new Request(url, init));
    throw new Error("Unexpected network request");
  }) as typeof fetch;
  try {
    const workerEnv = { MCP_AUTHORIZATION_SERVER: `${origin}/api/auth`, MCP_RESOURCE_URL: resource, MCP_ACCOUNT_SERVICE_SECRET: secret };
    const discovery = await worker.fetch(new Request(`${resource.replace('/mcp','')}/.well-known/oauth-protected-resource`), workerEnv);
    assert.equal((await discovery.json() as any).resource, resource);
    const unauthenticated = await worker.fetch(new Request(resource, { method: "POST" }), workerEnv);
    assert.equal(unauthenticated.status, 401);
    assert.match(unauthenticated.headers.get("www-authenticate")!, /oauth-protected-resource/);
    const list = await worker.fetch(new Request(resource, { method: "POST", headers: { Authorization: `Bearer ${refreshed.access_token}`, "Content-Type": "application/json", Accept: "application/json, text/event-stream" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/list" }) }), workerEnv);
    assert.equal(list.status, 200);
    const listed = await list.text();
    assert.match(listed, /market:read/);
    assert.match(listed, /company_profile/);
    await db.update(apiKey).set({ revokedAt: new Date() }).where(eq(apiKey.id, keyRecord.id));
    const revoked = await worker.fetch(new Request(resource, { method: "POST", headers: { Authorization: `Bearer ${refreshed.access_token}` } }), workerEnv);
    assert.equal(revoked.status, 401);
  } finally { globalThis.fetch = originalFetch; }
  assert((await call("/oauth2/token", tokenBody)).status >= 400, "code reuse must fail");
  await db.update(apiKey).set({ revokedAt: null }).where(eq(apiKey.id, keyRecord.id));
  await db.delete(oauthConsent).where(eq(oauthConsent.userId, uid));
  assert.equal((await bridge(refreshed.access_token)).status, 401);
});
