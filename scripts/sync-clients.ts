import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { agentTools } from '../packages/agent-tools/src/index.js';
import { tools as mcpTools } from '../apps/mcp/src/shared.js';

// Generate from local Rust source, never from a potentially stale deployed API.
const spec = JSON.parse(execFileSync('cargo', [
  'run', '--quiet', '--manifest-path', 'apps/api-rs/Cargo.toml', '--', '--export-openapi',
], { encoding: 'utf8', maxBuffer: 10 * 1024 * 1024 }));
// IPO is currently API-only; keep the existing MCP/CLI contract unchanged.
const publicTools = agentTools(spec).filter(tool => spec.paths[tool.path].get['x-resource'] !== 'ipo');
assert.ok(publicTools.length > 0, 'API export must contain public tools');
const paths = publicTools.map(tool => tool.path).sort();
assert.deepEqual(mcpTools.map(tool => tool.path).sort(), paths, 'MCP routes have drifted from the public API');
for (const tool of publicTools) {
  const mcp = mcpTools.find(candidate => candidate.path === tool.path)!;
  assert.deepEqual(Object.keys(mcp.schema).sort(), tool.parameters.map(parameter => parameter.name).sort(), `${tool.path}: MCP parameters have drifted`);
  for (const parameter of tool.parameters) {
    assert.equal(!mcp.schema[parameter.name].isOptional(), Boolean(parameter.required), `${tool.path}: ${parameter.name} required flag differs`);
  }
}
const catalog = { paths: Object.fromEntries(publicTools.map(tool => {
  const { responses: _responses, ...operation } = spec.paths[tool.path].get;
  return [tool.path, { get: operation }];
})) };
const output = '// Generated by pnpm sync:clients. Do not edit.\nexport const spec = ' + JSON.stringify(catalog, null, 2) + ' as const;\n';
const path = 'apps/legerline-cli/src/catalog.ts';
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(path, 'utf8'), output, 'CLI catalog is stale; run pnpm sync:clients');
} else {
  writeFileSync(path, output);
}
console.log(`Synced ${publicTools.length} public API contracts; MCP routes and parameters match.`);
