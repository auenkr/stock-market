import { readFile, mkdir, writeFile } from "node:fs/promises";
import { URL as NodeURL } from "node:url";
import { openApi } from "../src/openapi.js";
import { endpointCatalog } from "../src/endpoint-catalog.js";
import { coverageDetails } from "../src/coverage-details.js";

const spec = openApi(process.env.PUBLIC_URL || "http://localhost:8787");
const json = JSON.stringify(spec, null, 2) + "\n";
const root = new NodeURL("../../../", import.meta.url);
const inventory = `# Endpoint coverage\n\nGenerated by \`pnpm docs:generate\` from the same contract as Swagger and the docs page.\n\nInspected: ${spec["x-coverage-summary"].inspectedAt}. ${spec["x-coverage-summary"].total} reference paths: ${spec["x-coverage-summary"].partial} partial, ${spec["x-coverage-summary"].unavailable} unavailable (501), ${spec["x-coverage-summary"].excluded} market-history exclusions. Counts exclude aliases and legacy/service routes.\n\nPartial means an independently sourced subset, not full field or history parity.\n\n| Tier | Path | Status | Coverage / missing data |\n| --- | --- | --- | --- |\n` + endpointCatalog.map((e) => `| ${e.tier} | \`${e.path}\` | ${e.status} | ${(coverageDetails[e.resource] ?? e.limitation).replace(/\|/g, "\\|")} |`).join("\n") + "\n";
const artifacts = [["swagger.json", json], ["apps/web/public/swagger.json", json], ["docs/endpoint-coverage.md", inventory]] as const;
if (process.argv.includes("--check")) {
  for (const [path, content] of artifacts) if (await readFile(new NodeURL(path, root), "utf8") !== content) throw new Error(`${path} is stale; run pnpm docs:generate`);
  console.log("Swagger and coverage artifacts match the source contract.");
} else {
  await mkdir(new NodeURL("apps/web/public/", root), { recursive: true });
  for (const [path, content] of artifacts) await writeFile(new NodeURL(path, root), content);
  console.log(`Generated Swagger ${spec.info.version} and coverage inventory (${Object.keys(spec.paths).length} paths including aliases).`);
}
